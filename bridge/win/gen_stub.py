#!/usr/bin/env python3
"""Writes bridge/win/stub_api.inc, the Windows bridge's refusal stub OrtApi (the private Windows plan's R1,
bridge.md §3, r4:I46, J3), from clang's AST of the vendored ORT 1.18 header, built for the bridge's
own target (x86_64-w64-mingw32):

    clang -fsyntax-only -Xclang -ast-dump=json -Xclang -ast-dump-filter=OrtApi h.c > ast.json
    gen_stub.py ast.json > stub_api.inc

One typed function per OrtApi slot, filled into a typed `static const OrtApi stub_api` with
designated initializers: no void* table, no cast thunk, so a type that doesn't match its slot is a
compile error, and a _Static_assert in the includer checks every slot is filled. Bodies, as R1
says, none allocating (the stub may run in Demucs3.dll's DllMain):
  OrtStatus* slots              -> &stub_status, one static ORT_FAIL status (CreateStatus too: no
                                   copy of the message)
  GetErrorCode, GetErrorMessage -> read stub_status
  Release*, ClearBound*         -> nothing
  MemoryInfoGetDeviceType       -> writes the CPU device to its out-param
  GetBuildInfoString            -> a constant string
  GetTrainingApi                -> NULL
Any other return type stops the generator, so a new kind of slot can't slip through.

Path parameters are spelled ORTCHAR_T (the header's macro: wchar_t on Windows, char elsewhere), so
the same file also compiles against the Mac's view of the header, where bridge/win/tests/stub.c
calls every slot through the typed struct (the completeness check). Under STUB_SELFTEST the file
also defines stub_names[] and stub_call(), that call. The includer defines `stub_status`."""
import json
import re
import sys


def records(txt):
    dec = json.JSONDecoder()
    i = 0
    while True:
        j = txt.find("{", i)
        if j < 0:
            return
        o, i = dec.raw_decode(txt, j)
        yield o


def split_top(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def portable(t):
    t = t.replace(" __attribute__((stdcall))", "").replace("__attribute__((stdcall)) ", "")
    t = re.sub(r"\bwchar_t\b", "ORTCHAR_T", t)
    if "__attribute__" in t or "__declspec" in t:
        sys.exit("a Windows-only spelling left in %r" % t)
    return t


def parse(q):
    q = portable(q)
    k = q.index("(*)")
    ret = q[:k].strip()
    params = q[k + 3:].strip()
    assert params[0] == "(" and params[-1] == ")", q
    params = split_top(params[1:-1])
    if params == ["void"]:
        params = []
    return ret, params


def main():
    txt = open(sys.argv[1]).read()
    fields = None
    for r in records(txt):
        if r.get("kind") == "RecordDecl" and r.get("name") == "OrtApi" and r.get("completeDefinition"):
            fields = [f for f in r["inner"] if f["kind"] == "FieldDecl"]
            break
    if not fields:
        sys.exit("no OrtApi in the AST")
    out = ["/* Generated by bridge/win/gen_stub.py from bridge/onnxruntime_c_api.h (ONNX Runtime 1.18): the",
           " * refusal stub's %d OrtApi slots (the private Windows plan's R1, J3). Don't edit: bridge/win/build.sh" % len(fields),
           " * regenerates it and refuses a difference. */"]
    names, calls = [], []
    for idx, f in enumerate(fields):
        name = f["name"]
        ret, params = parse(f["type"]["qualType"])
        args = ", ".join("__typeof__(%s) p%d" % (p, n) for n, p in enumerate(params)) or "void"
        unused = " ".join("(void)p%d;" % n for n in range(len(params)))
        # pointers get a dummy non-NULL address (the Mac's header marks some slots nonnull), the rest 0
        zero = ["(__typeof__(%s))(void *)stub_arg" % p if p.rstrip().endswith("*") else "(__typeof__(%s)){0}" % p for p in params]
        kind = "STUB_STATUS"
        if ret in ("OrtStatus *", "OrtStatusPtr"):
            body = "return &stub_status;"
        elif name == "GetErrorCode":
            body, kind = "return stub_status.code;", "STUB_CODE"
        elif name == "GetErrorMessage":
            body, kind = "return stub_status.msg;", "STUB_TEXT"
        elif name == "MemoryInfoGetDeviceType":
            body, kind = "if (p1) *p1 = OrtMemoryInfoDeviceType_CPU;", "STUB_DEVICE"
            zero[1] = "&stub_device"
        elif name == "GetBuildInfoString":
            body, kind = 'return "RB Stems Plus bridge: ONNX Runtime unavailable";', "STUB_TEXT"
        elif name == "GetTrainingApi":
            body, kind = "return NULL;", "STUB_NULL"
        elif ret == "void" and (name.startswith("Release") or name.startswith("ClearBound")):
            body, kind = "", "STUB_VOID"
        else:
            sys.exit("unhandled slot %s returning %s" % (name, ret))
        out.append("static __typeof__(%s) ORT_API_CALL stub_%s(%s) { %s%s%s }"
                   % (ret, name, args, unused, " " if unused and body else "", body))
        names.append(name)
        call = "a->%s(%s)" % (name, ", ".join(zero))
        if kind == "STUB_VOID" or kind == "STUB_DEVICE":
            calls.append("    case %d: %s; return %s;" % (idx, call, kind))
        elif kind == "STUB_CODE":
            calls.append("    case %d: *ret = (uintptr_t)%s; return %s;" % (idx, call, kind))
        else:
            calls.append("    case %d: *ret = (uintptr_t)(const void *)%s; return %s;" % (idx, call, kind))
    out.append("#define STUB_SLOTS %d" % len(names))
    out.append("static const OrtApi stub_api = {")
    out += ["    .%s = stub_%s," % (n, n) for n in names]
    out.append("};")
    out.append("#ifdef STUB_SELFTEST")
    out.append("static const char *const stub_names[STUB_SLOTS] = {")
    out += ['    "%s",' % n for n in names]
    out.append("};")
    out.append("enum { STUB_STATUS, STUB_CODE, STUB_TEXT, STUB_DEVICE, STUB_NULL, STUB_VOID };")
    out.append("static OrtMemoryInfoDeviceType stub_device;")
    out.append("static long long stub_arg[64]; /* what every pointer argument points at: the stub never reads it */")
    out.append("/* calls slot i of a, through the typed struct: pointer arguments stub_arg, the others 0")
    out.append(" * (MemoryInfoGetDeviceType: &stub_device); *ret: what it returned. The slot's kind, or -1 past the")
    out.append(" * last. */")
    out.append("static int stub_call(const OrtApi *a, int i, uintptr_t *ret) {")
    out.append("    *ret = 0;")
    out.append("    switch (i) {")
    out += calls
    out.append("    default: return -1;")
    out.append("    }")
    out.append("}")
    out.append("#endif")
    print("\n".join(out))


if __name__ == "__main__":
    main()
