/* rekordbox's library, read only. master.db is a SQLCipher database in WAL mode; rekordbox writes
 * every change to the WAL at once and folds it in when it quits (measured). One read
 * transaction per read gives a consistent snapshot while rekordbox runs; the connection is read
 * only and never writes the file.
 *
 * The tables (measured): djmdPlaylist (ID, ParentID "root" at the top, Seq = rekordbox's
 * order, Attribute 0 playlist, 1 folder, 4 intelligent), djmdSongPlaylist (PlaylistID,
 * ContentID, TrackNo), djmdContent (ID, FolderPath); rows rekordbox deleted keep
 * rb_local_deleted = 1. */
#include "library.h"
#ifdef _WIN32
#include "plat_helper.h"
#else
#include <pwd.h>
#include <unistd.h>
#endif
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sqlite3.h>
#include "libkey.h"          /* generated by build.sh: LIBKEY, LIBKEY_LEN (masked) */

/* SQLCipher's (sqlite3.h declares it only when built with SQLITE_HAS_CODEC) */
int sqlite3_key(sqlite3 *db, const void *key, int n);

struct library { sqlite3 *db; };

#ifdef _WIN32
void library_default_path(char *buf, size_t n) {
    char d[1024];                           /* the account's AppData\Roaming from the shell, never %APPDATA% */
    buf[0] = 0;
    if (!plat_known_folder(PLAT_FOLDER_ROAMING_APPDATA, d, sizeof d)) snprintf(buf, n, "%s\\Pioneer\\rekordbox\\master.db", d);
}
#else
void library_default_path(char *buf, size_t n) {
    struct passwd pw, *res = NULL;          /* the account's home from the user database, never HOME */
    char b[16384];
    buf[0] = 0;
    if (getpwuid_r(getuid(), &pw, b, sizeof b, &res) == 0 && res && res->pw_dir[0] == '/')
        snprintf(buf, n, "%s/Library/Pioneer/rekordbox/master.db", res->pw_dir);
}
#endif

static void fail(sqlite3 *db, const char *what, char *why, size_t n) {
    snprintf(why, n, "rekordbox's library: %s: %s", what, db ? sqlite3_errmsg(db) : "out of memory");
}

library *library_open(const char *path, char *why, size_t n) {
    sqlite3 *db = NULL;
    if (sqlite3_open_v2(path, &db, SQLITE_OPEN_READONLY | SQLITE_OPEN_NOMUTEX, NULL) != SQLITE_OK) {
        fail(db, "can't open it", why, n);
        sqlite3_close(db);
        return NULL;
    }
    unsigned char key[LIBKEY_LEN];
    for (int i = 0; i < LIBKEY_LEN; i++) key[i] = (unsigned char)(LIBKEY[i] - 0x5a - 13 * i);
    int rc = sqlite3_key(db, key, LIBKEY_LEN);
#ifdef _WIN32
    SecureZeroMemory(key, sizeof key);                 /* the wipe stays */
#else
    memset(key, 0, sizeof key);
    __asm__ volatile("" : : "r"(key) : "memory");     /* the wipe stays */
#endif
    /* the first read proves the key (SQLCipher only checks it then) */
    if (rc == SQLITE_OK) rc = sqlite3_busy_timeout(db, 5000);
    if (rc == SQLITE_OK) rc = sqlite3_exec(db, "SELECT count(*) FROM sqlite_master", NULL, NULL, NULL);
    if (rc != SQLITE_OK) {
        fail(db, rc == SQLITE_NOTADB ? "not a rekordbox library this helper can read" : "can't read it", why, n);
        sqlite3_close(db);
        return NULL;
    }
    library *l = malloc(sizeof *l);
    if (!l) { sqlite3_close(db); snprintf(why, n, "out of memory"); return NULL; }
    l->db = db;
    return l;
}

void library_close(library *l) {
    if (!l) return;
    sqlite3_close(l->db);
    free(l);
}

static void json_str(FILE *f, const char *s) {
    fputc('"', f);
    for (const unsigned char *p = (const unsigned char *)(s ? s : ""); *p; p++) {
        if (*p == '"' || *p == '\\') fprintf(f, "\\%c", *p);
        else if (*p < 0x20) fprintf(f, "\\u%04x", *p);
        else fputc(*p, f);
    }
    fputc('"', f);
}

static const char *kind(int attribute) {
    switch (attribute) {
    case 0: return "playlist";
    case 1: return "folder";
    case 4: return "intelligent";
    default: return "other";
    }
}

/* one snapshot for the whole read */
static int begin(library *l, char *why, size_t n) {
    if (sqlite3_exec(l->db, "BEGIN", NULL, NULL, NULL) == SQLITE_OK) return 0;
    fail(l->db, "can't read it", why, n);
    return -1;
}
static void end(library *l) { sqlite3_exec(l->db, "COMMIT", NULL, NULL, NULL); }

int library_list(library *l, FILE *out, char *why, size_t n) {
    /* parents before children: walk down from "root", each level by Seq */
    static const char *q =
        "WITH RECURSIVE tree(ID, ParentID, Name, Attribute, Seq, depth, path) AS ("
        "  SELECT ID, ParentID, Name, Attribute, Seq, 0, printf('%010d', Seq) FROM djmdPlaylist"
        "   WHERE ParentID = 'root' AND rb_local_deleted = 0"
        "  UNION ALL"
        "  SELECT p.ID, p.ParentID, p.Name, p.Attribute, p.Seq, t.depth + 1,"
        "         t.path || '/' || printf('%010d', p.Seq) FROM djmdPlaylist p JOIN tree t ON p.ParentID = t.ID"
        "   WHERE p.rb_local_deleted = 0 AND t.depth < 64)"
        " SELECT t.ID, t.ParentID, t.Name, t.Attribute,"
        "  (SELECT count(*) FROM djmdSongPlaylist s JOIN djmdContent c ON c.ID = s.ContentID"
        "    WHERE s.PlaylistID = t.ID AND s.rb_local_deleted = 0 AND substr(c.FolderPath, 1, 1) = '/')"
        " FROM tree t ORDER BY t.path";
    if (begin(l, why, n)) return -1;
    sqlite3_stmt *st = NULL;
    if (sqlite3_prepare_v2(l->db, q, -1, &st, NULL) != SQLITE_OK) { fail(l->db, "can't list its playlists", why, n); end(l); return -1; }
    int rc;
    while ((rc = sqlite3_step(st)) == SQLITE_ROW) {
        int attr = sqlite3_column_int(st, 3);
        fprintf(out, "{\"playlist\":");
        json_str(out, (const char *)sqlite3_column_text(st, 0));
        fprintf(out, ",\"parent\":");
        json_str(out, (const char *)sqlite3_column_text(st, 1));
        fprintf(out, ",\"name\":");
        json_str(out, (const char *)sqlite3_column_text(st, 2));
        fprintf(out, ",\"kind\":\"%s\",\"tracks\":%d}\n", kind(attr), attr == 0 ? sqlite3_column_int(st, 4) : 0);
    }
    if (rc != SQLITE_DONE) fail(l->db, "can't list its playlists", why, n);
    sqlite3_finalize(st);
    end(l);
    fflush(out);
    return rc == SQLITE_DONE ? 0 : -1;
}

int library_tracks(library *l, const char *id, char ***paths, size_t *count, char *why, size_t n) {
    *paths = NULL;
    *count = 0;
    if (begin(l, why, n)) return -1;
    sqlite3_stmt *st = NULL;
    int ret = -1, rc;
    if (sqlite3_prepare_v2(l->db, "SELECT Attribute, Name FROM djmdPlaylist WHERE ID = ? AND rb_local_deleted = 0",
                           -1, &st, NULL) != SQLITE_OK) { fail(l->db, "can't read its playlists", why, n); goto out; }
    sqlite3_bind_text(st, 1, id, -1, SQLITE_TRANSIENT);
    rc = sqlite3_step(st);
    if (rc != SQLITE_ROW) {
        if (rc == SQLITE_DONE) snprintf(why, n, "rekordbox's library has no playlist %s", id);
        else fail(l->db, "can't read its playlists", why, n);
        goto out;
    }
    int attr = sqlite3_column_int(st, 0);
    if (attr != 0) {
        snprintf(why, n, "%s is %s, not a playlist", (const char *)sqlite3_column_text(st, 1),
                 attr == 1 ? "a folder" : attr == 4 ? "an intelligent playlist" : "not a plain playlist");
        goto out;
    }
    sqlite3_finalize(st);
    /* the query measured against rekordbox's own list: in order, duplicates included */
    if (sqlite3_prepare_v2(l->db,
                           "SELECT c.FolderPath FROM djmdSongPlaylist s JOIN djmdContent c ON c.ID = s.ContentID"
                           " WHERE s.PlaylistID = ? AND s.rb_local_deleted = 0 ORDER BY s.TrackNo",
                           -1, &st, NULL) != SQLITE_OK) { st = NULL; fail(l->db, "can't read the playlist", why, n); goto out; }
    sqlite3_bind_text(st, 1, id, -1, SQLITE_TRANSIENT);
    size_t cap = 64;
    char **p = malloc(sizeof(char *) * cap);
    if (!p) { snprintf(why, n, "out of memory"); goto out; }
    while ((rc = sqlite3_step(st)) == SQLITE_ROW) {
        const char *path = (const char *)sqlite3_column_text(st, 0);
        if (!path || path[0] != '/') continue;           /* a streaming track: left alone */
        size_t k = 0;
        while (k < *count && strcmp(p[k], path)) k++;     /* each path once, first place kept */
        if (k < *count) continue;
        if (*count == cap) {
            char **q = realloc(p, sizeof(char *) * (cap *= 2));
            if (!q) { rc = SQLITE_NOMEM; break; }
            p = q;
        }
        if (!(p[*count] = strdup(path))) { rc = SQLITE_NOMEM; break; }
        (*count)++;
    }
    if (rc != SQLITE_DONE) {
        if (rc == SQLITE_NOMEM) snprintf(why, n, "out of memory");
        else fail(l->db, "can't read the playlist", why, n);
        for (size_t k = 0; k < *count; k++) free(p[k]);
        free(p);
        *count = 0;
        goto out;
    }
    *paths = p;
    ret = 0;
out:
    sqlite3_finalize(st);
    end(l);
    return ret;
}
