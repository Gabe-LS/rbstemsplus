static void swift(void) {
    puts("// Generated by core/tools/gen_ids.c from core/*.def (the Mac build). Do not edit.");
    puts("// The shell refuses to start when core_ids_hash() differs (a stale archive).");
    printf("let coreIdsHash: UInt64 = 0x%016llx\n", (unsigned long long)ids_hash_compute());
}

int main(int argc, char **argv) {
    if (argc == 2 && !strcmp(argv[1], "cs")) cs();
    else if (argc == 2 && !strcmp(argv[1], "swift")) swift();
    else {
        fputs("usage: gen_ids cs|swift\n", stderr);
        return 2;
    }
    return 0;
}
