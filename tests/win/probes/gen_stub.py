#!/usr/bin/env python3
"""Generates the stub OrtApi of the Windows plan §4 R1 (r4:I46, J3) from clang's AST of the vendored
ORT 1.18 header: one typed function per OrtApi slot, filled into a typed `const OrtApi` with
designated initializers (no void* table, no cast thunk; a type mismatch is a compile error).

    clang -fsyntax-only -Xclang -ast-dump=json -Xclang -ast-dump-filter=OrtApi h.c > ast.json
    gen_stub.py ast.json > stub_api.inc

The includer defines STUB_TRACE(index, name, nargs, args...) (empty in a real bridge; the
arguments come as unsigned long long) and provides
`stub_status` (the static ORT_FAIL status). Bodies:
  OrtStatus* entries        -> &stub_status (CreateStatus too: static, no copy of the message)
  GetErrorCode/Message      -> read stub_status
  void entries (Release*, ClearBound*) -> nothing; MemoryInfoGetDeviceType writes CPU
  GetBuildInfoString        -> a constant; GetTrainingApi -> NULL
Any other return type stops the generator, so a new kind of slot can't slip through."""
import json
import re
import sys


def records(txt):
    dec = json.JSONDecoder()
    i = 0
    while True:
        j = txt.find("{", i)
        if j < 0:
            return
        o, i = dec.raw_decode(txt, j)
        yield o


def split_top(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def parse(q):
    q = q.replace(" __attribute__((stdcall))", "")
    k = q.index("(*)")
    ret = q[:k].strip()
    params = q[k + 3:].strip()
    assert params[0] == "(" and params[-1] == ")", q
    params = split_top(params[1:-1])
    if params == ["void"]:
        params = []
    return ret, params


def main():
    txt = open(sys.argv[1]).read()
    fields = None
    for r in records(txt):
        if r.get("kind") == "RecordDecl" and r.get("name") == "OrtApi" and r.get("completeDefinition"):
            fields = [f for f in r["inner"] if f["kind"] == "FieldDecl"]
            break
    if not fields:
        sys.exit("no OrtApi in the AST")
    print("/* generated by tests/win/probes/gen_stub.py: %d OrtApi slots */" % len(fields))
    names = []
    for idx, f in enumerate(fields):
        name = f["name"]
        ret, params = parse(f["type"]["qualType"])
        args = ", ".join("__typeof__(%s) p%d" % (p, n) for n, p in enumerate(params)) or "void"
        unused = " ".join("(void)p%d;" % n for n in range(len(params)))
        if ret in ("OrtStatus *", "OrtStatusPtr"):
            body = "return &stub_status;"
            # the probe's "late failure" variant (STUB_LATE true): object constructors and option
            # setters succeed (a constructor hands out a static dummy object), so the caller's
            # set-up runs as with a real runtime and only creating a session fails. A real bridge
            # defines STUB_LATE as 0: R1's stub, every status slot failing.
            last = params[-1] if params else ""
            ctor = re.match(r"^(Create|Clone)", name) and re.match(r"^Ort\w+ \*\*$", last) \
                and not (name.startswith("CreateSession") and name != "CreateSessionOptions") and name != "CreateStatus"
            setter = re.match(r"^(Set|Enable|Disable|Add|SessionOptions)", name)
            if ctor:
                body = "if (STUB_LATE) { if (p%d) *p%d = (__typeof__(*p%d))(void *)&stub_dummy; return NULL; } %s" \
                    % (len(params) - 1, len(params) - 1, len(params) - 1, body)
            elif setter:
                body = "if (STUB_LATE) return NULL; " + body
        elif name == "GetErrorCode":
            body = "return stub_status.code;"
        elif name == "GetErrorMessage":
            body = "return stub_status.msg;"
        elif name == "MemoryInfoGetDeviceType":
            body = "if (p1) *p1 = OrtMemoryInfoDeviceType_CPU;"
        elif name == "GetBuildInfoString":
            body = 'return "RB Stems Plus stub (ONNX Runtime unavailable)";'
        elif name == "GetTrainingApi":
            body = "return NULL;"
        elif ret == "void" and (name.startswith("Release") or name.startswith("ClearBound")):
            body = ""
        else:
            sys.exit("unhandled slot %s returning %s" % (name, ret))
        targs = "".join(", (unsigned long long)(uintptr_t)p%d" % n for n in range(len(params)))
        print("static __typeof__(%s) ORT_API_CALL stub_%s(%s) { %s STUB_TRACE(%d, \"%s\", %d%s); %s }"
              % (ret, name, args, unused, idx, name, len(params), targs, body))
        names.append(name)
    print("#define STUB_SLOTS %d" % len(names))
    print("static const char *const stub_names[STUB_SLOTS] = {%s};" % ", ".join('"%s"' % n for n in names))
    print("static const OrtApi stub_api = {")
    for n in names:
        print("    .%s = stub_%s," % (n, n))
    print("};")


if __name__ == "__main__":
    main()
